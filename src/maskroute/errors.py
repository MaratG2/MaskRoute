"""Stable error codes; exception text never contains caller data."""

from enum import StrEnum


class Code(StrEnum):
    OK = "OK"
    SESSION_CLOSED = "SESSION_CLOSED"
    INVALID_SCHEMA = "INVALID_SCHEMA"
    UNKNOWN_REFERENCE = "UNKNOWN_REFERENCE"
    UNISSUED_REFERENCE = "UNISSUED_REFERENCE"
    REVOKED_REFERENCE = "REVOKED_REFERENCE"
    WRONG_KIND = "WRONG_KIND"
    METADATA_CONFLICT = "METADATA_CONFLICT"
    TOKEN_LIKE_TEXT = "TOKEN_LIKE_TEXT"
    UNKNOWN_TOOL = "UNKNOWN_TOOL"
    POLICY_DENIED = "POLICY_DENIED"
    UNAUTHORIZED = "UNAUTHORIZED"
    AUTHORIZER_REQUIRED = "AUTHORIZER_REQUIRED"
    AUTHORIZATION_TIMEOUT = "AUTHORIZATION_TIMEOUT"
    PROVIDER_FAILED = "PROVIDER_FAILED"
    TOOL_FAILED = "TOOL_FAILED"
    UNCLASSIFIED_OUTPUT = "UNCLASSIFIED_OUTPUT"
    FORBIDDEN_OUTPUT = "FORBIDDEN_OUTPUT"
    UNSAFE_SURFACE = "UNSAFE_SURFACE"


class MaskRouteError(Exception):
    def __init__(self, code: Code) -> None:
        self.code = code
        super().__init__(code.value)
